function suitableFoodNotes(category) {
  if (category === 'smoothie_shake') {
    return 'Liten, kaloririk shake. God når du trenger noe søtt som likevel gir protein.';
  }
  if (category === 'dinner') {
    return 'Liten hovedrett. Salt og mettende — porsjoner i matboks eller fryser.';
  }
  if (category === 'soup') {
    return 'Varm, myk suppe i liten bolle. Lett å spise når en stor middag føles for mye.';
  }
  if (category === 'dessert') {
    return 'Liten kake, pudding eller godteri-bit med næring. Tell den som et måltid.';
  }
  return 'Lite mellommåltid — søtt eller salt. Noe lite er nok, og det teller.';
}

