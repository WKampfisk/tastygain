/** Sørg for beholderinfo, foto og egnet-mat-tekst på alle oppskrifter */
export function enrichRecipe(recipe) {
  if (!recipe) return recipe;
  const withMedia = withRecipeMedia(recipe);
  const flavor_tags =
    withMedia.flavor_tags?.length > 0
      ? withMedia.flavor_tags
      : FLAVOR_BY_ID[withMedia.id] ||
        (withMedia.category === 'dessert' || withMedia.category === 'smoothie_shake'
          ? ['sweet']
          : ['salty']);
  return {
    ...withMedia,
    flavor_tags,
    protein_g: withMedia.protein_g ?? PROTEIN_BY_ID[withMedia.id] ?? null,
    suitable_food_notes: withMedia.suitable_food_notes || suitableFoodNotes(withMedia.category),
    containers:
      withMedia.containers?.length > 0
        ? withMedia.containers
        : defaultContainersForCategory(withMedia.category),
  };
}

export function enrichRecipes(list) {
  return (list || []).map(enrichRecipe);
}

