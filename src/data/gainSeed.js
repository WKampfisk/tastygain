function multiPrice(baseOre) {
  return CHAINS.map((chain, i) => ({
    chain,
    price_ore: baseOre + (i % 3) * 100 - 50,
    is_on_sale: i === 1,
  }));
}

function p(row) {
  return {
    ...row,
    available_chains: row.available_chains || CHAINS,
    prices: row.prices || multiPrice(row.price_ore || 2990),
  };
}

